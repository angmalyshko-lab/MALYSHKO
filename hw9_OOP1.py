# Задача 2 (раздел: Конструктор класса __init__)

# Создай класс Dog.
# Внутри класса определи конструктор __init__, который принимает
# два параметра (кроме self): name и age.
# Внутри конструктора сохрани эти значения в атрибуты объекта
# с такими же именами: self.name и self.age.

class Dog:
    def __init__(self, name, age):
        self.name = name
        self.age = age

