# Задача 7
# Создай два списка:
# list1 = [1, 2, 3]
# list2 = [4, 5, 6]
# Объедини их в один список с именем result двумя способами:
# 1) с помощью оператора +
# 2) с помощью метода extend()
# Выведи оба результата на экран.

list_1 = [1, 2, 3]
list_2 = [4, 5, 6]
result_1 = list_1 + list_2
list_1.extend(list_2)
print(result_1)
print(list_1)

