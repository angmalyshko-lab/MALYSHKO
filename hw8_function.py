# Задача 4 (декораторы)
#
# Напиши декоратор с именем announce, который перед вызовом
# декорируемой функции печатает строку "Начинаю выполнение...".
#
# Затем создай простую функцию say_hello, которая печатает "Привет!"
# и оберни её этим декоратором через @announce.
#
# Вызови say_hello() один раз.

def announce(func):
    def wrapper():
        print("Начинаю выполнение...")
        func()
    return wrapper
@announce
def say_hello():
    print("Привет!")
say_hello()

