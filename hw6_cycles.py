# Задача 6
# Дан список чисел: numbers = [1, 2, 3, 4, 5, 6, 7, 8]
# Используя цикл for и остановку цикла, выведи числа, начиная с 1,
# но останови вывод, как только встретишь число 6 (само число 6 выводить не нужно).

numbers = [1, 2, 3, 4, 5, 6, 7, 8]
for number in numbers:
    if number >= 6:
        break
    else:
        print(number)
