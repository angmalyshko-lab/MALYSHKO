# Задача 1
# Дан список чисел: numbers = [3, 8, 1, 6, 4]
# Используя цикл for, выведи каждый элемент списка на экран.

numbers = [3, 8, 1, 6, 4]
for number in numbers:
    print(number)

# Задача 2
