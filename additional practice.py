# - иначе выведи "Маленькое: <число>"
# Используй f-строку для вывода.

numbers = [3, 7, 12, 5, 9]

for number in numbers:
    if number > 10:
        print(f"Большое: {number}")
    else:
        print(f"Маленькое: {number}")

