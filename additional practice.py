# Задача 24.
# Напиши функцию с именем count_up, которая принимает один аргумент n.
# Функция должна вывести на экран все числа от 1 до n включительно
# с помощью цикла for и функции range.
# Затем вызови функцию с аргументом 5.

def count_up(n):
    for i in range(1, n + 1):
        print(i)
count_up(5)

# Задача 25.
# Создай класс Book.
# В конструкторе __init__ задай два атрибута: self.title и self.author (принимаются аргументами).
# Добавь метод info, который возвращает строку в формате:
# "<title> — <author>"
# Затем:
# 1. Создай объект с title="Война и мир" и author="Толстой".
# 2. Выведи результат вызова метода info.

class Book:
    def __init__(self, title, author):
        self.title = title
        self.author = author
    def info(self):
        return f"{self.title} - {self.author}"
my_book = Book("Война и мир","Толстой")
print(my_book.info())
