# Задача 22.
# Создай класс Circle.
# В конструкторе __init__ задай атрибут self.radius (принимается аргументом).
# Добавь метод area, который возвращает площадь круга: 3.14 * radius ** 2.
# Затем:
# 1. Создай объект с радиусом 5.
# 2. Выведи площадь через вызов метода area.

class Circle:
    def __init__(self, radius):
        self.radius = radius
    def area(self):
        return 3.14 * self.radius ** 2
the_circle = Circle(5)
print(the_circle.area())

